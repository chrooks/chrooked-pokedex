"""Redux Mode on Essentials 21 (Nova): every battler has all of its species' abilities (#121).

Rejuv's Redux Mode (`references/rejuv-harness/chrooked_zz_redux.rb`) makes the
battler's ability a set whose `==` matches any of them, because Rejuv checks
abilities in ~1650 separate places. Nova routes almost every check through two
Seams, so its Redux composes the battler's abilities the way a composed ability
composes its parts (`behavior.compose`):

  * Handler registries. `Battler#ability` hands the battle code a copy of the
    primary ability's GameData that carries the battler's list. Every registry's
    `trigger` (and `[]`, which the AI asks) runs each listed ability's handler,
    combined by `ChrookedCompose.combine`'s rule for that registry.
  * Checks by name. `hasActiveAbility?` (the AI's `has_active_ability?`
    delegates) answers yes for any listed ability, and for a composed one's parts.

The list is the species' regular and hidden abilities, the battler's own first.
It is empty, so the battler has its one ability as before, while the option is
Off, after its ability changes (Skill Swap, Trace, Mummy) and while it is
Transformed. The ability box names the primary, and Nova's 14 direct
`ability_id ==` checks see only the primary.

The file is generated, not hand-written, so it carries the one ChrookedCompose
(and ChrookedLog) the composed abilities share; it sorts after them, so theirs
loads first. It is a static mod: apply installs it unless the Target turns it
off (`ruleset/targets/<slug>/mods.yaml`), and the in-game option starts Off.
"""

from __future__ import annotations

from .compose import _COMPOSE
from .templates import _CHROOKED_LOG

FILE = "chrooked_zz_redux.rb"

_HEADER = """\
# chrooked:zz_redux
# mod-group: battle
# mod-summary: Redux Mode option: every battler has all of its species' abilities at once (Off by default)
# GENERATED by chrooked-pokedex (behavior/redux.py). Do not edit this file.
# Options > Gameplay > Redux Mode. When On, each battler, yours and the foe's,
# has its species' regular and hidden abilities active together. Its ability
# box still names its own ability.
# ponytail: Skill Swap / Trace / Mummy / Transform collapse it to one ability
# for the rest of the battle, and Nova's 14 direct ability_id checks see only
# the primary. Upgrade path: keep a changed ability's list (Rejuv has the same
# ceiling).
"""

_REDUX = """\
class PokemonSystem
  attr_writer :chrooked_redux

  # nil on a save from before this mod: Off.
  def chrooked_redux
    @chrooked_redux || 0
  end
end

MenuHandlers.add(:options_menu, :chrooked_redux, {
  "page"        => :gameplay,
  "name"        => _INTL("Redux Mode"),
  "order"       => 80,
  "type"        => :array,
  "parameters"  => [_INTL("Off"), _INTL("On")],
  "description" => _INTL("Choose whether every Pokémon in battle has all of its species' abilities at once."),
  "get_proc"    => proc { next $PokemonSystem.chrooked_redux },
  "set_proc"    => proc { |value, _screen| $PokemonSystem.chrooked_redux = value }
})

module ChrookedRedux
  @held = {}
  @names = {}.compare_by_identity

  def self.on?
    $PokemonSystem.respond_to?(:chrooked_redux) && $PokemonSystem.chrooked_redux == 1
  end

  # The primary ability's GameData, copied once per list, carrying the list.
  # It is still a GameData::Ability, so == :INTIMIDATE, .name and try_get work.
  def self.held(ability, ids)
    @held[ids] ||= ability.dup.tap { |a| a.instance_variable_set(:@chrooked_redux, ids.freeze) }
  end

  # The abilities a held copy carries; nil for a Symbol or a plain ability.
  def self.ids_of(sym)
    sym.instance_variable_get(:@chrooked_redux) if sym.is_a?(GameData::Ability)
  end

  # A registry's constant name, for its merge rule.
  def self.name_of(registry)
    if @names.empty?
      Battle::AbilityEffects.constants.each do |name|
        hash = Battle::AbilityEffects.const_get(name)
        @names[hash] = name if hash.is_a?(HandlerHashSymbol)
      end
    end
    @names[registry]
  end
end

class AbilityHandlerHash
  alias_method :chrooked_redux_lookup, :[]
  def [](sym)
    ids = ChrookedRedux.ids_of(sym)
    return chrooked_redux_lookup(sym) if ids.nil?
    ids.each { |id| handler = chrooked_redux_lookup(id); return handler if handler }
    nil
  end

  alias_method :chrooked_redux_trigger, :trigger
  def trigger(sym, *args)
    ids = ChrookedRedux.ids_of(sym)
    return chrooked_redux_trigger(sym, *args) if ids.nil?
    # Each listed ability's handler gets its own id, as if it were the battler's only one.
    handlers = ids.filter_map do |id|
      handler = chrooked_redux_lookup(id)
      handler && [id.to_s.downcase, proc { |_sym, *rest| handler.call(id, *rest) }]
    end
    return nil if handlers.empty?
    ChrookedCompose.combine(ChrookedRedux.name_of(self), nil, handlers).call(sym.id, *args)
  rescue StandardError => e
    ChrookedLog.error("[chrooked:zz_redux] ERROR #{ChrookedRedux.name_of(self)} #{e.class}: #{e.message}")
    raise
  end
end

class Battle::Battler
  # The battler's species abilities, its own first; empty when Redux is Off, its
  # ability changed (Skill Swap, Trace, Mummy) or it is Transformed.
  # ponytail: rebuilt on every call; memoize per species and form if it shows up in a profile.
  def chrooked_redux_ids
    return [] if !ChrookedRedux.on? || @pokemon.nil? || @ability_id.nil?
    return [] if @ability_id != @pokemon.ability_id || (@effects && @effects[PBEffects::Transform])
    species = @pokemon.species_data
    ids = ([@ability_id] + species.abilities + species.hidden_abilities).compact.uniq
    ids.select { |id| GameData::Ability.exists?(id) }
  end

  alias_method :chrooked_redux_ability, :ability
  def ability
    held = chrooked_redux_ability
    return held if held.nil?
    ids = chrooked_redux_ids
    ids.length > 1 ? ChrookedRedux.held(held, ids) : held
  end

  alias_method :chrooked_redux_has_active_ability?, :hasActiveAbility?
  def hasActiveAbility?(check_ability, ignore_fainted = false)
    return true if chrooked_redux_has_active_ability?(check_ability, ignore_fainted)
    ids = chrooked_redux_ids
    return false if ids.length < 2 || !abilityActive?(ignore_fainted, check_ability)
    checks = check_ability.is_a?(Array) ? check_ability : [check_ability]
    ids.any? { |id| ([id] + (ChrookedCompose.parts_of(id) || [])).any? { |a| checks.include?(a) } }
  end
  alias hasWorkingAbility hasActiveAbility?
end
"""


def render_essentials21() -> str:
    """The Redux Mode file, `chrooked_zz_redux.rb`."""
    return "\n".join([
        _HEADER,
        _CHROOKED_LOG,
        _COMPOSE,
        "begin",
        _REDUX,
        '  ChrookedLog.line("[chrooked:zz_redux] installed; Off until the option is On")',
        "rescue StandardError => e",
        '  ChrookedLog.error("[chrooked:zz_redux] ERROR #{e.class}: #{e.message}")',
        "end",
        "",
    ])
